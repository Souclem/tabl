/// Libellé français d'une catégorie Foursquare. Une catégorie inconnue
/// garde son nom d'origine plutôt que de disparaître.
String libelleCategorie(String categorie) {
  final nom = categorie.trim();
  final exact = _libelles[nom];
  if (exact != null) return exact;
  const suffixe = ' Restaurant';
  if (nom.endsWith(suffixe)) {
    final cuisine = _cuisines[nom.substring(0, nom.length - suffixe.length)];
    if (cuisine != null) return cuisine;
  }
  return categorie;
}

/// Version simplifiée d'un nom pour la recherche : minuscules, sans
/// accents — même résultat que `lower(unaccent(...))` côté base pour
/// les caractères courants, afin que les restaurants créés depuis l'app
/// soient retrouvables comme ceux de l'annuaire.
String normaliserPourRecherche(String texte) {
  const accents = {
    'à': 'a',
    'á': 'a',
    'â': 'a',
    'ã': 'a',
    'ä': 'a',
    'å': 'a',
    'ç': 'c',
    'è': 'e',
    'é': 'e',
    'ê': 'e',
    'ë': 'e',
    'ì': 'i',
    'í': 'i',
    'î': 'i',
    'ï': 'i',
    'ñ': 'n',
    'ò': 'o',
    'ó': 'o',
    'ô': 'o',
    'õ': 'o',
    'ö': 'o',
    'ù': 'u',
    'ú': 'u',
    'û': 'u',
    'ü': 'u',
    'ý': 'y',
    'ÿ': 'y',
    'œ': 'oe',
    'æ': 'ae',
    '¡': '!',
    '¿': '?',
  };
  final minuscules = texte.trim().toLowerCase();
  final resultat = StringBuffer();
  for (final caractere in minuscules.split('')) {
    resultat.write(accents[caractere] ?? caractere);
  }
  return resultat.toString();
}
